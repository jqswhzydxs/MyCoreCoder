"""Generate or validate the benchmark evidence block embedded in both READMEs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .compare import compare_payloads, load_report

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "evals" / "results"
GATES = ROOT / "evals" / "gates.json"
README_PATHS = (ROOT / "README.md", ROOT / "README_CN.md")
START = "<!-- eval-benchmark:start -->"
END = "<!-- eval-benchmark:end -->"

METRICS = (
    ("Task success rate", "task_success_rate", True),
    ("Verified completion rate", "verified_completion_rate", True),
    ("False completion rate", "false_completion_rate", True),
    ("Duplicate side-effect rate", "duplicate_side_effect_rate", True),
    ("Permission bypass rate", "permission_bypass_rate", True),
    ("Crash resume rate", "crash_resume_rate", True),
    ("P95 rounds", "p95_rounds", False),
    ("Completion tokens", "completion_tokens", False),
)


def _display(value: float | None, *, percentage: bool) -> str:
    if value is None:
        return "unavailable"
    if percentage:
        return f"{value * 100:.4f}".rstrip("0").rstrip(".") + "%"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def benchmark_block() -> str:
    baseline = load_report(RESULTS / "baseline.json")
    candidate = load_report(RESULTS / "candidate.json")
    gates = json.loads(GATES.read_text(encoding="utf-8"))
    comparison = compare_payloads(baseline, candidate, gates)
    metadata = candidate["metadata"]

    lines = [
        START,
        "<!-- Generated by: python -m evals.readme_benchmark --write -->",
        "| Metric | Baseline | Candidate |",
        "|---|---:|---:|",
    ]
    for label, key, percentage in METRICS:
        lines.append(
            f"| {label} | {_display(baseline['metrics'][key], percentage=percentage)} "
            f"| {_display(candidate['metrics'][key], percentage=percentage)} |"
        )
    lines.extend(
        [
            "",
            (
                f"Evidence: {metadata['case_count']} deterministic offline cases, "
                f"{metadata['run_count']} run per case, model "
                f"`{metadata['model']['type']}/{metadata['model']['name']}`, "
                f"commit `{metadata['git_commit']}`. Safety gates: "
                f"**{'PASS' if comparison['gate_passed'] else 'FAIL'}**."
            ),
            END,
        ]
    )
    return "\n".join(lines)


def _replace_block(text: str, block: str, path: Path) -> str:
    if text.count(START) != 1 or text.count(END) != 1:
        raise ValueError(f"{path} must contain exactly one benchmark marker pair")
    before, remainder = text.split(START, 1)
    _, after = remainder.split(END, 1)
    return before + block + after


def update_readmes(*, check: bool) -> list[str]:
    block = benchmark_block()
    stale: list[str] = []
    for path in README_PATHS:
        current = path.read_text(encoding="utf-8")
        expected = _replace_block(current, block, path)
        if current == expected:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8")
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Update both README blocks.")
    mode.add_argument("--check", action="store_true", help="Fail if either block is stale.")
    args = parser.parse_args(argv)
    check = not args.write
    stale = update_readmes(check=check)
    if stale:
        print("Stale README benchmark block(s): " + ", ".join(stale))
        print("Run: python -m evals.readme_benchmark --write")
        return 1
    print("README benchmark blocks are current." if check else "README benchmark blocks updated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
